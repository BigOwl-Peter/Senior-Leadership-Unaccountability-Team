import type {
  DepartmentId,
  EventChoice,
  GameEvent,
  GameEffect,
} from '../models/game';
import type { Conversation } from './teams';
const fx = (
  type: Exclude<GameEffect['type'], 'WORKLOAD'>,
  amount: number,
): GameEffect => ({ type, amount });
const work = (departmentId: DepartmentId, amount: number): GameEffect => ({
  type: 'WORKLOAD',
  departmentId,
  amount,
});
const choice = (
  id: string,
  label: string,
  description: string,
  effects: GameEffect[],
  follow?: string,
  probability = 1,
): EventChoice => ({
  id,
  label,
  description,
  immediateEffects: effects,
  ...(follow
    ? { followUps: [{ eventId: follow, delay: 45, probability }] }
    : {}),
});
function scenario(
  id: string,
  owner: DepartmentId,
  title: string,
  proposal: string,
  opposingTeam: DepartmentId,
  objection: string,
  choices: EventChoice[],
  defaultChoice: string,
  options: Partial<GameEvent> = {},
): { event: GameEvent; conversation: Conversation } {
  return {
    event: {
      id,
      title,
      category: options.followUpOnly ? 'Follow-up decision' : 'Team decision',
      departmentId: owner,
      workload: 45,
      description: proposal,
      choices,
      ...options,
    },
    conversation: {
      owner,
      subject: title,
      proposal,
      defaultChoice,
      objection: { team: opposingTeam, text: objection },
      reply:
        'The deadline is approaching. We need a decision before the fallback becomes the plan.',
    },
  };
}
